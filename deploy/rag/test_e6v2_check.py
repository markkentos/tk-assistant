# -*- coding: utf-8 -*-
"""Проверка: e6v2 по памяти (без контекста) — сквозь host.docker.internal."""
import sys

import httpx

sys.stdout.reconfigure(encoding="utf-8")

SYSTEM = (
    "Ты — ассистент по трудовому праву РФ. Отвечай на вопросы, опираясь на "
    "Трудовой кодекс РФ. Формат ответа — строго две части:\n"
    "1) краткий ответ одним предложением;\n"
    "2) обоснование из 1–3 предложений со ссылкой на статью в формате «ст. N ТК РФ».\n"
    "Не выдумывай номера статей. Если не уверен — так и скажи."
)

QUESTIONS = [
    ("Сколько дней отпуска положено работнику в возрасте до 18 лет?",
     "ожидаю: 31 календарный день, ст. 267"),
    ("За сколько дней работник должен предупредить работодателя "
     "об увольнении по собственному желанию?",
     "ожидаю: 2 недели, ст. 80"),
    ("Какой максимальный размер среднего месячного заработка "
     "при взыскании ущерба?", "ожидаю: 1 среднемесячный заработок, ст. 241"),
]

for q, expect in QUESTIONS:
    r = httpx.post("http://host.docker.internal:8080/v1/chat/completions",
                   json={"messages": [{"role": "system", "content": SYSTEM},
                                      {"role": "user", "content": q}],
                         "max_tokens": 120, "temperature": 0.2, "stream": False},
                   timeout=180)
    print(f"Q: {q}\n   [{expect}]")
    try:
        print("A:", r.json()["choices"][0]["message"]["content"].strip(), "\n")
    except Exception as e:
        print("ОШИБКА:", e, r.text[:200], "\n")
